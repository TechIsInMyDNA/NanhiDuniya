SEEN_NAMES = set()

def clean_letter(hindi_syllable: str) -> str:
    matras = ['ा', 'ि', 'ी', 'ु', 'ू', 'ृ', 'े', 'ै', 'ो', 'ौ', 'ं', 'ः']
    clean = hindi_syllable
    for m in matras:
        clean = clean.replace(m, '')
    return clean.strip()

def generate_ai_names(hindi_letter: str, gender: str = "All", mode: str = "strict"):
    global SEEN_NAMES

    # 1. Select Roots & Suffixes by Mode
    if mode == "strict":
        b_roots, b_sufs = STRICT_VEDIC_ROOTS_BOY, STRICT_SUFFIXES_BOY
        g_roots, g_sufs = STRICT_VEDIC_ROOTS_GIRL, STRICT_SUFFIXES_GIRL
    else:
        b_roots, b_sufs = ANUMATI_VEDIC_ROOTS_BOY, ANUMATI_SUFFIXES_BOY
        g_roots, g_sufs = ANUMATI_VEDIC_ROOTS_GIRL, ANUMATI_SUFFIXES_GIRL

    # 2. Build Massive Vedic Sandhi Combinations
    boy_synthesized = []
    # Base classical names
    for r_name, r_mean, r_sig in b_roots:
        boy_synthesized.append((r_name, r_name, r_mean, r_sig))
    # Sandhi compound Vedic names
    for r_name, r_mean, r_sig in b_roots:
        for s_hi, s_en, s_mean, s_sig in b_sufs:
            full_name = f"{r_name}{s_hi}"
            full_mean = f"{r_mean}, {s_mean}"
            full_sig = f"{r_sig}; {s_sig}"
            boy_synthesized.append((full_name, full_name, full_mean, full_sig))

    girl_synthesized = []
    # Base classical names
    for r_name, r_mean, r_sig in g_roots:
        girl_synthesized.append((r_name, r_name, r_mean, r_sig))
    # Sandhi compound Vedic names
    for r_name, r_mean, r_sig in g_roots:
        for s_hi, s_en, s_mean, s_sig in g_sufs:
            full_name = f"{r_name}{s_hi}"
            full_mean = f"{r_mean}, {s_mean}"
            full_sig = f"{r_sig}; {s_sig}"
            girl_synthesized.append((full_name, full_name, full_mean, full_sig))

    # 3. Filter unseen names for zero repetition
    avail_boys = [item for item in boy_synthesized if item[0] not in SEEN_NAMES]
    avail_girls = [item for item in girl_synthesized if item[0] not in SEEN_NAMES]

    # Memory auto-clear if pool exhausted (rarely happens with thousands of combos)
    if len(avail_boys) < 6:
        avail_boys = boy_synthesized
        SEEN_NAMES.clear()
    if len(avail_girls) < 6:
        avail_girls = girl_synthesized
        SEEN_NAMES.clear()

    random.shuffle(avail_boys)
    random.shuffle(avail_girls)

    results = []

    if gender in ["Boy", "All"]:
        count = 3 if gender == "All" else 6
        for name_hi, name_en, mean, sig in avail_boys[:count]:
            SEEN_NAMES.add(name_hi)
            results.append({
                "name_hi": name_hi,
                "name_en": name_en,
                "gender": "Boy",
                "meaning": mean,
                "significance": sig
            })

    if gender in ["Girl", "All"]:
        count = 3 if gender == "All" else 6
        for name_hi, name_en, mean, sig in avail_girls[:count]:
            SEEN_NAMES.add(name_hi)
            results.append({
                "name_hi": name_hi,
                "name_en": name_en,
                "gender": "Girl",
                "meaning": mean,
                "significance": sig
            })

    random.shuffle(results)
    return results[:6]

