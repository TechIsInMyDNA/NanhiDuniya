def clean_syllable(s):
    for m in ['ा', 'ि', 'ी', 'ु', 'ू', 'ृ', 'े', 'ै', 'ो', 'ौ', 'ं', 'ः']:
        s = s.replace(m, '')
    return s.strip()

def generate_ai_names(letter, gender="All", mode="strict"):
    base_char = clean_syllable(letter)
    
    # 1. Selection Strategy based on mode
    pool = None
    if mode == "strict":
        # Strict mode: First check exact syllable (e.g. 'तू' or 'तु')
        if letter in VEDIC_LEXICON_EXACT:
            pool = VEDIC_LEXICON_EXACT[letter]
        elif base_char == "त" and letter in ["तू", "तु"]:
            pool = VEDIC_LEXICON_EXACT.get("तू")
    
    # If not strict or exact pool not found, use permitted class (varga)
    if not pool:
        pool = VEDIC_LEXICON_EXACT.get(base_char) or VEDIC_LEXICON_EXACT.get(letter)

    boys = []
    girls = []

    if pool:
        for b in pool.get("Boy", []):
            boys.append({"name_hi": b[0], "name_en": b[1], "gender": "Boy", "meaning": b[2], "significance": b[3]})
        for g in pool.get("Girl", []):
            girls.append({"name_hi": g[0], "name_en": g[1], "gender": "Girl", "meaning": g[2], "significance": g[3]})

    # Fallback to universal pool if letter is not in primary list
    if not boys:
        for u in UNIVERSAL_BACKUP["Boy"]:
            boys.append({"name_hi": u[0], "name_en": u[1], "gender": "Boy", "meaning": u[2], "significance": u[3]})
    if not girls:
        for u in UNIVERSAL_BACKUP["Girl"]:
            girls.append({"name_hi": u[0], "name_en": u[1], "gender": "Girl", "meaning": u[2], "significance": u[3]})

    # Filter strictly by gender
    if gender == "Boy":
        final_list = boys
    elif gender == "Girl":
        final_list = girls
    else:
        final_list = boys + girls

    # Shuffle to give random fresh order on each click
    random.shuffle(final_list)
    return final_list[:12]
