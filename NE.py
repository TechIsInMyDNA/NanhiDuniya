def sanskrit_sandhi_combine(root_hi, root_en, suffix_hi, suffix_en):
    # Strip halant safely
    clean_r_hi = root_hi[:-1] if root_hi.endswith('्') else root_hi

    # High precision vowel sandhi rules (स्वर संधि)
    if suffix_hi == "ईश":
        combined_hi = clean_r_hi + "ेश"
    elif suffix_hi == "इंद्र":
        combined_hi = clean_r_hi + "ेंद्र"
    elif suffix_hi == "अंश":
        combined_hi = clean_r_hi + "ांश" if not clean_r_hi.endswith(('ा', 'ि', 'ी', 'ु', 'ू')) else clean_r_hi + "ंश"
    elif suffix_hi == "आनंद":
        combined_hi = clean_r_hi + "ानंद"
    elif suffix_hi == "इत":
        combined_hi = clean_r_hi + "ित"
    elif suffix_hi == "िक":
        combined_hi = clean_r_hi + "िक"
    elif suffix_hi == "ा":
        combined_hi = clean_r_hi + "ा" if not clean_r_hi.endswith(('ा', 'ि', 'ी', 'ु', 'ू')) else clean_r_hi
    elif suffix_hi == "ी":
        combined_hi = clean_r_hi + "ी" if not clean_r_hi.endswith(('ा', 'ि', 'ी', 'ु', 'ू')) else clean_r_hi
    elif suffix_hi == "िका":
        combined_hi = clean_r_hi + "िका"
    elif suffix_hi == "िता":
        combined_hi = clean_r_hi + "िता"
    elif suffix_hi == "्या":
        combined_hi = clean_r_hi + "्या"
    else:
        combined_hi = clean_r_hi + suffix_hi

    clean_r_en = root_en.rstrip('a').rstrip('h')
    if suffix_en.startswith(('a', 'e', 'i', 'o', 'u')):
        combined_en = (clean_r_en + suffix_en).title()
    else:
        combined_en = (root_en + suffix_en).title()

    return combined_hi, combined_en

def clean_syllable(s):
    for m in ['ा', 'ि', 'ी', 'ु', 'ू', 'ृ', 'े', 'ै', 'ो', 'ौ', 'ं', 'ः']:
        s = s.replace(m, '')
    return s.strip()

def get_varga_category(char):
    # Mapping consonants to their respective Paninian Varga
    mapping = {
        "क": "क", "ख": "ख", "ग": "ग", "घ": "घ",
        "च": "च", "छ": "छ", "ज": "ज", "झ": "झ",
        "ट": "ट", "ठ": "ट", "ड": "ड", "ढ": "ड", "ण": "ड",
        "त": "त", "थ": "त", "द": "द", "ध": "ध", "न": "न",
        "प": "प", "फ": "प", "ब": "ब", "भ": "भ", "म": "म",
        "य": "य", "र": "र", "ल": "ल", "व": "व",
        "श": "श", "ष": "श", "स": "स", "ह": "ह"
    }
    return mapping.get(char, "अ")

def generate_ai_names(letter, gender="All", mode="strict"):
    base_char = clean_syllable(letter)
    varga_key = get_varga_category(base_char)

    # 1. Fetch relevant roots for this sound
    roots = ALL_VARGA_ROOTS.get(varga_key) or ALL_VARGA_ROOTS.get(base_char) or ALL_VARGA_ROOTS["त"]

    generated_boys = []
    generated_girls = []
    seen = set()

    # Determine match prefix for Strict mode
    # If letter has matra (e.g. 'तू' or 'खी' or 'चे'), respect that sound
    strict_prefix = letter
    is_u_matra = any(u in letter for u in ['ु', 'ू'])
    is_i_matra = any(i in letter for i in ['ि', 'ी'])

    # Synthesize Boys
    for r_hi, r_en, r_mean, r_sig in roots:
        for s_hi, s_en, s_mean in BOY_PRATYAYAS:
            n_hi, n_en = sanskrit_sandhi_combine(r_hi, r_en, s_hi, s_en)

            if mode == "strict":
                if is_u_matra and not (n_hi.startswith(base_char + "ु") or n_hi.startswith(base_char + "ू")):
                    continue
                elif is_i_matra and not (n_hi.startswith(base_char + "ि") or n_hi.startswith(base_char + "ी")):
                    continue
                elif not is_u_matra and not is_i_matra and not n_hi.startswith(base_char):
                    continue

            if n_hi not in seen:
                seen.add(n_hi)
                generated_boys.append({
                    "name_hi": n_hi,
                    "name_en": n_en,
                    "gender": "Boy",
                    "meaning": f"{r_mean}, {s_mean}",
                    "significance": r_sig
                })

    # Synthesize Girls
    for r_hi, r_en, r_mean, r_sig in roots:
        for s_hi, s_en, s_mean in GIRL_PRATYAYAS:
            n_hi, n_en = sanskrit_sandhi_combine(r_hi, r_en, s_hi, s_en)

            if mode == "strict":
                if is_u_matra and not (n_hi.startswith(base_char + "ु") or n_hi.startswith(base_char + "ू")):
                    continue
                elif is_i_matra and not (n_hi.startswith(base_char + "ि") or n_hi.startswith(base_char + "ी")):
                    continue
                elif not is_u_matra and not is_i_matra and not n_hi.startswith(base_char):
                    continue

            if n_hi not in seen:
                seen.add(n_hi)
                generated_girls.append({
                    "name_hi": n_hi,
                    "name_en": n_en,
                    "gender": "Girl",
                    "meaning": f"{r_mean}, {s_mean}",
                    "significance": r_sig
                })

    # Filter by gender
    if gender == "Boy":
        final_list = generated_boys
    elif gender == "Girl":
        final_list = generated_girls
    else:
        final_list = generated_boys + generated_girls

    # If strict filter yielded few results, broaden slightly while preserving root integrity
    if len(final_list) < 6:
        for r_hi, r_en, r_mean, r_sig in roots:
            for s_hi, s_en, s_mean in (BOY_PRATYAYAS if gender == "Boy" else GIRL_PRATYAYAS if gender == "Girl" else BOY_PRATYAYAS + GIRL_PRATYAYAS):
                n_hi, n_en = sanskrit_sandhi_combine(r_hi, r_en, s_hi, s_en)
                if n_hi not in seen:
                    seen.add(n_hi)
                    final_list.append({
                        "name_hi": n_hi,
                        "name_en": n_en,
                        "gender": "Boy" if s_hi in [x[0] for x in BOY_PRATYAYAS] else "Girl",
                        "meaning": f"{r_mean}, {s_mean}",
                        "significance": r_sig
                    })

    random.shuffle(final_list)
    return final_list[:12]
