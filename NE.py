def clean_syllable(s):
    # Remove all matras to get the base consonant/vowel
    for m in ['ा', 'ि', 'ी', 'ु', 'ू', 'ृ', 'े', 'ै', 'ो', 'ौ', 'ं', 'ः']:
        s = s.replace(m, '')
    return s.strip()

def generate_ai_names(letter, gender="All", mode="strict"):
    cleaned = clean_syllable(letter)
    root_category = VARGA_MAP.get(letter) or VARGA_MAP.get(cleaned) or "अ"
    
    pool = VEDIC_LEXICON_DB.get(root_category, VEDIC_LEXICON_DB["अ"])
    
    boys = []
    girls = []

    # Filter boys
    for item in pool.get("Boy", []):
        if mode == "strict":
            # In strict mode, prioritize matching starting syllable if available
            if item[0].startswith(letter) or item[0].startswith(cleaned):
                boys.append({"name_hi": item[0], "name_en": item[1], "gender": "Boy", "meaning": item[2], "significance": item[3]})
        else:
            boys.append({"name_hi": item[0], "name_en": item[1], "gender": "Boy", "meaning": item[2], "significance": item[3]})

    # Filter girls
    for item in pool.get("Girl", []):
        if mode == "strict":
            if item[0].startswith(letter) or item[0].startswith(cleaned):
                girls.append({"name_hi": item[0], "name_en": item[1], "gender": "Girl", "meaning": item[2], "significance": item[3]})
        else:
            girls.append({"name_hi": item[0], "name_en": item[1], "gender": "Girl", "meaning": item[2], "significance": item[3]})

    # Fallback if strict pool was small
    if not boys:
        for item in pool.get("Boy", []):
            boys.append({"name_hi": item[0], "name_en": item[1], "gender": "Boy", "meaning": item[2], "significance": item[3]})
    if not girls:
        for item in pool.get("Girl", []):
            girls.append({"name_hi": item[0], "name_en": item[1], "gender": "Girl", "meaning": item[2], "significance": item[3]})

    results = []
    if gender in ["Boy", "All"]:
        results.extend(boys[:4 if gender == "All" else 6])
    if gender in ["Girl", "All"]:
        results.extend(girls[:4 if gender == "All" else 6])

    random.shuffle(results)
    return results
